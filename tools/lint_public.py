#!/usr/bin/env python3
"""Public-repository guard: tracked text must carry no provenance and no machine-specific names.

Usage: python tools/lint_public.py [--path <checkout>] [--report] [--update-baseline]

Scans every tracked (or new, not ignored) text file (not addons/, .beads/, binaries or CLAUDE.local.md) with the rules in
tools/public_rules.py: Beads ids, dates, who-asked tags in comments and docs,
drive-letter paths, user folders and user names. A line containing `lint-public: allow <reason>` is
exempt (genuine fixtures only). tools/public_baseline.json holds today's findings outside tools/
(`findings`: {path: {rule: count}}); a (file, rule) count above its baseline fails; entries that no longer occur are reported as
STALE, and the baseline only shrinks: --update-baseline lowers or removes entries, never adds or raises one. tools/ has no baseline.
Clean a file with tools/scrub_provenance.py, then run --update-baseline.
Prints one `LINT PUBLIC GREEN|RED` line (exit 1 on RED); --report lists every finding.
"""
from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
from typing import Dict, List, Tuple

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import public_rules as pr  # noqa: E402

BASELINE_NAME = "public_baseline.json"
SKIP_PREFIXES = ("addons/", ".beads/", ".git/", ".godot/")
SKIP_FILES = ("CLAUDE.local.md",)
# Baselines in tools/ quote game-code lines (their text is the key); they are regenerated by the
# lints' own --update commands after the game-code pass, so they are not scanned.
SKIP_PATTERNS = ("tools/", "_baseline.json")
BINARY_EXTS = (".png", ".jpg", ".jpeg", ".webp", ".gif", ".ico", ".wav", ".ogg", ".mp3", ".glb", ".gltf", ".fbx",
               ".obj", ".blend", ".ttf", ".otf", ".woff", ".woff2", ".zip", ".7z", ".dll", ".exe", ".pck", ".so",
               ".dylib", ".bin", ".pdf", ".psd", ".kra", ".mp4", ".webm", ".res", ".scn", ".ctex", ".svg", ".uid")
SNIFF_BYTES = 8192
Findings = Dict[str, Dict[str, int]]


def tracked(root: str) -> List[str]:
    p = subprocess.run(["git", "-C", root, "ls-files", "-z", "--cached", "--others", "--exclude-standard"], capture_output=True, text=True,
                       encoding="utf-8", errors="replace", timeout=120)
    return [x for x in p.stdout.split("\0") if x] if p.returncode == 0 else []


def read_text(root: str, rel: str):
    if rel.startswith(SKIP_PATTERNS[0]) and rel.endswith(SKIP_PATTERNS[1]):
        return None
    if rel in SKIP_FILES or rel.startswith(SKIP_PREFIXES) or rel.lower().endswith(BINARY_EXTS):
        return None
    full = os.path.join(root, rel)
    try:
        with open(full, "rb") as fh:
            raw = fh.read()
    except OSError:
        return None
    if b"\0" in raw[:SNIFF_BYTES]:
        return None
    try:
        return raw.decode("utf-8")
    except UnicodeDecodeError:
        return None


def scan(root: str) -> Tuple[Findings, List[Tuple[str, int, str, str]]]:
    counts: Findings = {}
    detail: List[Tuple[str, int, str, str]] = []
    for rel in tracked(root):
        text = read_text(root, rel)
        if text is None:
            continue
        for ln, rid, txt in pr.find_issues(rel, text.replace("\r\n", "\n")):
            counts.setdefault(rel, {}).setdefault(rid, 0)
            counts[rel][rid] += 1
            detail.append((rel, ln, rid, txt))
    return counts, detail


def load_baseline(path: str) -> Findings:
    try:
        with open(path, encoding="utf-8") as fh:
            return json.load(fh).get("findings", {})
    except (OSError, ValueError):
        return {}


def compare(counts: Findings, base: Findings) -> Tuple[List[str], List[str]]:
    """(new findings, stale baseline entries)."""
    new: List[str] = []
    stale: List[str] = []
    for rel, rules in sorted(counts.items()):
        for rid, n in sorted(rules.items()):
            allowed = base.get(rel, {}).get(rid, 0)
            if n > allowed:
                new.append("%s: %s x%d (baseline %d)" % (rel, rid, n, allowed))
    for rel, rules in sorted(base.items()):
        for rid, n in sorted(rules.items()):
            if counts.get(rel, {}).get(rid, 0) < n:
                stale.append("%s: %s baseline %d, now %d" % (rel, rid, n, counts.get(rel, {}).get(rid, 0)))
    return new, stale


def shrink(counts: Findings, base: Findings) -> Findings:
    """The baseline after --update-baseline: every entry capped at its current count, none added."""
    out: Findings = {}
    for rel, rules in base.items():
        for rid, n in rules.items():
            cur = min(n, counts.get(rel, {}).get(rid, 0))
            if cur > 0:
                out.setdefault(rel, {})[rid] = cur
    return out


def main(argv: List[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--path", default=os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    ap.add_argument("--report", action="store_true")
    ap.add_argument("--update-baseline", action="store_true")
    ap.add_argument("--init-baseline", action="store_true", help=argparse.SUPPRESS)
    args = ap.parse_args(argv)
    root = os.path.abspath(args.path)
    base_path = os.path.join(root, "tools", BASELINE_NAME)
    counts, detail = scan(root)
    base = load_baseline(base_path)
    if args.init_baseline and not base:
        seed = {rel: r for rel, r in counts.items() if not rel.startswith("tools/")}
        with open(base_path, "w", encoding="utf-8", newline="\n") as fh:
            json.dump({"findings": seed}, fh, indent=1, sort_keys=True)
            fh.write("\n")
        base = seed
    if args.update_baseline:
        shrunk = shrink(counts, base)
        with open(base_path, "w", encoding="utf-8", newline="\n") as fh:
            json.dump({"findings": shrunk}, fh, indent=1, sort_keys=True)
            fh.write("\n")
        base = shrunk
    if args.report:
        for rel, ln, rid, txt in detail:
            print("%s:%d: %s: %s" % (rel, ln, rid, txt))
    new, stale = compare(counts, base)
    for line in new:
        print("NEW " + line)
    for line in stale:
        print("STALE " + line)
    total = sum(sum(r.values()) for r in counts.values())
    if new:
        print("LINT PUBLIC RED: %d new finding group(s); clean them (tools/scrub_provenance.py) or add "
              "`lint-public: allow <reason>` to a genuine fixture line" % len(new))
        return 1
    print("LINT PUBLIC GREEN: %d findings, all baselined (%d files, %d stale baseline entries)"
          % (total, len(counts), len(stale)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
